//! `TestApp` factory: builds a fresh DB pool, applies migrations,
//! constructs `AppState`, and wraps it in an `axum_test::TestServer`
//! with cookies enabled.
//!
//! Each test gets its own pool. The pool is backed by a temp-file
//! SQLite database (rather than `sqlite::memory:`) because sqlx's
//! pool keeps multiple connections, and an in-memory database
//! gives each connection its own private memory space — making
//! the second connection see an empty DB. A temp file gives a
//! shared backing store, and SQLite's WAL mode keeps it well-
//! behaved for the test's lifetime.
//!
//! Temp directories are allocated by `tempfile::TempDir`
//! (`QA-001`, baseline `§10.13`). An earlier version named the
//! directory from `SystemTime::now().as_nanos()` alone; two tests
//! entering `spawn` within the same clock tick got the same
//! directory and the same `test.db`, and `create_dir_all` succeeds
//! on an existing directory, so nothing signalled the collision —
//! the second arrival just failed against a database mid-migration
//! or already locked. `tempfile` guarantees a unique path by
//! construction (pid, a process-local atomic counter, and
//! randomness — not just the clock), and the `TempDir` handle held
//! on `TestApp` removes the directory on drop, closing the "these
//! accumulate under `/tmp` forever" half of the same finding.

use std::time::Duration;

use axum_test::TestServer;
use peisear_storage::{Pool, pool};
use peisear_web::{AppState, build_router};
#[cfg(feature = "sqlite")]
use tempfile::TempDir;

/// The fixed JWT secret every `TestApp` uses. Exported so
/// `common::auth::requester_id_for` can mint and verify tokens that are
/// valid against the same app a test spun up (`PRIV-002`).
pub const JWT_SECRET: &str = "test-jwt-secret-must-not-be-used-in-production";

/// A running test instance of the peisear application. Holds the
/// backing isolation handle so it lives exactly as long as the
/// `TestApp` does and is cleaned up when it drops — a `TempDir` on
/// SQLite (free per-test isolation from a unique temp file) or a
/// `peisear_storage::pool::TestDatabase` on PostgreSQL (`CON-003`:
/// one server, so isolation is a database created and migrated for
/// this test alone, not something a temp file gives for free there).
pub struct TestApp {
    pub server: TestServer,
    pub db: Pool,
    #[cfg(feature = "sqlite")]
    _temp_dir: TempDir,
    #[cfg(all(feature = "postgres", not(feature = "sqlite")))]
    _test_database: pool::TestDatabase,
}

impl TestApp {
    /// Spin up a fresh test app with a unique DB file. Migrations
    /// are applied. The JWT secret is fixed for tests so tokens
    /// generated by helpers stay valid across the same test.
    #[cfg(feature = "sqlite")]
    pub async fn spawn() -> Self {
        // `DOC-007` §3, measured 2026-10-13 on this machine (AMD Ryzen 9
        // 9950X, NVMe, LUKS/Btrfs): `cargo test --workspace --locked`,
        // three runs each. Default root (`std::env::temp_dir()`, `/tmp`,
        // `tmpfs`): 32.28s / 32.39s / 31.51s, mean 32.06s. Pointed at a
        // disk-backed directory under `.git-exclude/tmp/` instead: 52.82s
        // / 49.64s / 41.98s (first run of three discarded -- it included
        // a rebuild after the harness edit, not steady-state), mean
        // 48.15s. **~1.5x slower on disk, and not within noise**: the
        // slowest tmpfs run (32.39s) is still faster than the fastest
        // disk run (41.98s), with no overlap between the two spreads.
        // **Left on tmpfs.** The architect's own prior was to move it if
        // the cost is small; 50% on every `cargo test --workspace`
        // invocation -- which `DEC-007` runs three times per release, and
        // every contributor runs routinely -- is not small. The failure
        // mode this leaves is written down instead: a `500` from any one
        // of the ~33 integration-test files using `TestApp::spawn` can
        // mean `/tmp` filled, not a broken lock (`DOC-004`'s own flake).
        // `/tmp` filling is a scratch-hygiene problem with its own fix
        // (`.github/CONTRIBUTING.md`'s "remove a scratch build's target
        // directory" step), not a reason to move every test database off
        // the fast path.
        let temp_dir = tempfile::Builder::new()
            .prefix("peisear-web-it-")
            .tempdir()
            .expect("create test temp dir");
        let url = format!("sqlite://{}/test.db", temp_dir.path().display());

        let db = pool::connect(&url)
            .await
            .unwrap_or_else(|e| panic!("connect test pool at {}: {e}", temp_dir.path().display()));
        pool::migrate(&db)
            .await
            .unwrap_or_else(|e| panic!("apply migrations at {}: {e}", temp_dir.path().display()));

        let state = AppState {
            db: db.clone(),
            jwt_secret: JWT_SECRET.into(),
            // cookie_secure=false so the auth cookie is sent over
            // the test server's plain HTTP. Production sets this
            // to true via Config::from_env.
            cookie_secure: false,
        };

        let router = build_router(state);

        // Save cookies across requests so that calls after `login`
        // carry the auth cookie automatically.
        //
        // axum-test 20 exposes this via `TestServer::builder()`
        // returning a `TestServerBuilder` whose `.build(router)`
        // returns a `TestServer` directly (no fallible Result).
        // expect_success_by_default is OFF by default, which is
        // what we want — handlers legitimately return 4xx (auth,
        // 403, 409, validation) and the tests assert explicitly.
        let server = TestServer::builder().save_cookies().build(router);

        Self {
            server,
            db,
            _temp_dir: temp_dir,
        }
    }

    /// `CON-003`'s own counterpart to the SQLite body above: one
    /// server, so isolation is a database created and migrated for
    /// this test alone (`pool::connect_isolated_test_database`)
    /// rather than a temp file. Everything from `AppState` down is
    /// identical to the SQLite body — the two bodies differ only in
    /// how the database the rest of this function uses comes to
    /// exist.
    #[cfg(all(feature = "postgres", not(feature = "sqlite")))]
    pub async fn spawn() -> Self {
        // `SUP-002`: a bare `500` names nothing -- `peisear_web::error`
        // already logs the real `sqlx` error via `tracing::error!` at
        // every call site, this just gives it somewhere to go. Every
        // defect this round found was read from this output, not
        // guessed from the response body. `try_init` because
        // `cargo test`'s own process can call `spawn` more than once;
        // a second global-subscriber install would panic otherwise.
        let _ = tracing_subscriber::fmt()
            .with_env_filter("error")
            .try_init();
        let test_database = pool::connect_isolated_test_database().await;
        let db = test_database.pool().clone();

        let state = AppState {
            db: db.clone(),
            jwt_secret: JWT_SECRET.into(),
            cookie_secure: false,
        };

        let router = build_router(state);
        let server = TestServer::builder().save_cookies().build(router);

        Self {
            server,
            db,
            _test_database: test_database,
        }
    }
}

/// Convenience for one-off tests.
pub async fn spawn() -> TestApp {
    TestApp::spawn().await
}

/// Sleep briefly so a subsequent write to the same row produces
/// a strictly-later `updated_at` timestamp. SQLite's
/// `CURRENT_TIMESTAMP` has whole-second precision, so without a
/// pause two writes in the same second would compare equal —
/// breaking optimistic-lock tests that rely on `updated_at` as
/// the version.
pub async fn ensure_distinct_timestamp() {
    tokio::time::sleep(Duration::from_millis(1100)).await;
}
